export type TranslationKey = keyof (typeof messages)['en'];

export const normalizeLocale = (value?: string | null): SupportedLocale | null => {
  const code = value?.split('-')[0]?.toLowerCase();
  if (code === 'es') return 'es';
  if (code === 'en') return 'en';
  return null;
};

export const pickSupportedLocale = (value?: string | null): SupportedLocale =>
  normalizeLocale(value) ?? defaultLocale;

const isJestRuntime = () => typeof process !== 'undefined' && !!process.env.JEST_WORKER_ID;

export const resolveLocale = (): SupportedLocale => {
  const candidates: Array<string | undefined> = [
    Platform.OS === 'ios'
      ? NativeModules.SettingsManager?.settings?.AppleLocale
      : NativeModules.I18nManager?.localeIdentifier,
    NativeModules.I18nManager?.localeIdentifier,
    NativeModules.SettingsManager?.settings?.AppleLocale,
    NativeModules.SettingsManager?.settings?.AppleLanguages?.[0],
  ];

  if (!isJestRuntime()) {
    candidates.push(
      typeof navigator !== 'undefined' ? navigator.language : undefined,
      typeof Intl !== 'undefined' ? Intl.DateTimeFormat().resolvedOptions().locale : undefined,
    );
  }

  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }

  return defaultLocale;
};

const LocaleContext = createContext<{ locale: SupportedLocale; t: (key: TranslationKey) => string }>({
  locale: defaultLocale,
  t: (key) => messages[defaultLocale][key],
});

export function AppLocaleProvider({ children }: { children: ReactNode }) {
  const locale = useMemo(() => resolveLocale(), []);
  const value = useMemo(
    () => ({
      locale,
      t: (key: TranslationKey) => messages[locale][key] ?? messages[defaultLocale][key],
    }),
    [locale],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
